import React from 'react';
import { motion, useReducedMotion } from 'framer-motion';

type SurveyOption = {
  id: string;
  label: string;
  count: number;
  accurate: boolean;
};

const QUESTION =
  'How would you describe \u201cCertainty of lift detection\u201d in the context of your brand lift results?';
const INSTRUCTION = 'Select all that apply';
const TAKEAWAY =
  'Most people can describe what \u201cCertainty of lift detection\u201d means';

const OPTIONS: SurveyOption[] = [
  {
    id: 'statistical-significance',
    label: 'The statistical significance of your lift results',
    count: 47,
    accurate: true,
  },
  {
    id: 'survey-reliability',
    label: 'The reliability of the brand lift survey responses',
    count: 39,
    accurate: true,
  },
  {
    id: 'likelihood-not-chance',
    label:
      'The likelihood your lift was generated by your campaigns, not chance',
    count: 31,
    accurate: true,
  },
  {
    id: 'completion-rate',
    label: 'The completion rate of the brand lift study',
    count: 13,
    accurate: false,
  },
  {
    id: 'other',
    label: 'Other / None of the above',
    count: 2,
    accurate: false,
  },
];

function ResponseBarChart({
  options,
  reduceMotion,
}: {
  options: SurveyOption[];
  reduceMotion: boolean | null;
}) {
  const max = Math.max(...options.map((option) => option.count), 1);

  return (
    <div>
      <div className="flex flex-wrap items-center gap-5 font-body text-sm text-color-text-primary">
        <span className="flex items-center gap-2">
          <span
            aria-hidden="true"
            className="h-3 w-3 rounded-sm bg-[var(--color-blue-500)]"
          />
          Accurate description
        </span>
        <span className="flex items-center gap-2">
          <span
            aria-hidden="true"
            className="h-3 w-3 rounded-sm bg-color-bg-subtle ring-1 ring-color-border-default"
          />
          Not accurate
        </span>
      </div>

      <ul className="mt-5 space-y-4">
        {options.map((option, index) => {
          const pct = (option.count / max) * 100;

          return (
            <li key={option.id}>
              <p
                id={`flexible-lift-survey-${option.id}-label`}
                className="font-body text-sm text-color-text-primary"
              >
                {option.label}
              </p>
              <div className="mt-1.5 flex items-center gap-3 pr-8">
                <motion.div
                  role="meter"
                  aria-labelledby={`flexible-lift-survey-${option.id}-label`}
                  aria-valuenow={option.count}
                  aria-valuemin={0}
                  aria-valuemax={max}
                  aria-valuetext={`${option.count} responses, ${
                    option.accurate ? 'accurate description' : 'not accurate'
                  }`}
                  initial={reduceMotion ? false : { width: 0 }}
                  animate={{ width: `${pct}%` }}
                  transition={
                    reduceMotion
                      ? { duration: 0 }
                      : {
                          duration: 0.6,
                          delay: 0.2 + index * 0.08,
                          ease: [0.22, 1, 0.36, 1],
                        }
                  }
                  className={`h-7 min-w-[0.5rem] rounded-sm ${
                    option.accurate
                      ? 'bg-[var(--color-blue-500)]'
                      : 'bg-color-bg-subtle ring-1 ring-inset ring-color-border-default'
                  }`}
                />
                <span className="shrink-0 font-heading text-sm font-semibold tabular-nums text-color-text-primary">
                  {option.count}
                </span>
              </div>
            </li>
          );
        })}
      </ul>
    </div>
  );
}

export function FlexibleLiftSurveyResults() {
  const reduceMotion = useReducedMotion();
  const total = OPTIONS.reduce((sum, option) => sum + option.count, 0);
  const accurateCount = OPTIONS.filter((option) => option.accurate).reduce(
    (sum, option) => sum + option.count,
    0,
  );
  const share = total > 0 ? Math.round((accurateCount / total) * 100) : 0;

  return (
    <section
      aria-labelledby="flexible-lift-survey-takeaway"
      className="my-5 grid w-full gap-8 border border-color-border-default bg-color-bg-surface px-6 py-8 first:mt-0 last:mb-0 sm:px-8 md:grid-cols-[minmax(0,1fr)_minmax(0,1.3fr)] md:gap-10 md:p-10"
    >
      <div className="flex flex-col">
        <figure className="rounded-sm bg-color-bg-subtle p-5">
          <blockquote className="font-heading text-lg font-semibold leading-snug text-color-text-primary">
            {QUESTION}
          </blockquote>
          <figcaption className="mt-2 font-body text-sm text-color-text-primary">
            {INSTRUCTION}
          </figcaption>
        </figure>

        <div className="mt-auto pt-8 md:pt-10">
          <motion.p
            initial={reduceMotion ? false : { opacity: 0, y: 8 }}
            animate={{ opacity: 1, y: 0 }}
            transition={reduceMotion ? { duration: 0 } : { duration: 0.4 }}
            className="font-heading text-5xl font-semibold tabular-nums text-[var(--color-blue-500)] sm:text-6xl"
          >
            {share}%
          </motion.p>
          <h3
            id="flexible-lift-survey-takeaway"
            className="mt-2 font-heading text-2xl font-semibold leading-tight text-color-text-primary"
          >
            {TAKEAWAY}
          </h3>
          <p className="mt-2 font-body text-sm text-color-text-primary">
            {accurateCount} of {total} selections chose an accurate description.
          </p>
        </div>
      </div>

      <ResponseBarChart options={OPTIONS} reduceMotion={reduceMotion} />
    </section>
  );
}
